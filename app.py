@app.route("/tool_types")
def tool_types():
    categories = db.session.execute(
        db.select(Tool.category).distinct()
    ).scalars().all()

    coded_limits = {
        "Vacuum Pumps": 1,
        "Recovery Machines": 2,
        "Hand Tools": 5
    }

    tool_type_summary = []
    for category in categories:
        available_count = Tool.query.filter_by(
            category=category, 
            status="Available"
        ).count()

        limit = coded_limits.get(category, 0)
        
        is_low = available_count <= limit

        tool_type_summary.append({
            "category": category,
            "available_count": available_count,
            "warning_limit": limit,
            "is_low": is_low
        })
    return render_template("tool_types.html", tool_types=tool_type_summary)

@app.route("/change_password", methods=["GET", "POST"])
def change_password():
    #check if user is signed in
    user_email = session['user_email'].strip()
    print("Session email:", repr(user_email))

    # Find the employee by email
    user = Employee.query.filter_by(email=user_email).first()

    if user is None:
        print("Employee not found in database.")
        flash("Employee not found.", "error")
        return redirect(url_for("login"))

    
    if request.method == "POST":
        current_password = request.form.get("current_password", "").strip()
        new_password = request.form.get("new_password", "").strip()
        confirm_password = request.form.get("confirm_password", "").strip()

        # Validate the form inputs
        if not current_password or not new_password or not confirm_password:
            flash("All fields are required.", "error")
        elif new_password != confirm_password:
            flash("New password and confirmation do not match.", "error")
        elif not bcrypt.checkpw(current_password.encode('utf-8'), user.password_hash.encode('utf-8')):
            flash("Current password is incorrect.", "error")
        else:
            # Hash the new password
            hashed_password = bcrypt.hashpw(new_password.encode('utf-8'), bcrypt.gensalt())

            # Update the user's password
            user.password_hash = hashed_password
            db.session.commit()

            return redirect(url_for("dashboard"))

    return render_template("change_pass.html")

