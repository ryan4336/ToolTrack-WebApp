    employee = db.get_or_404(Employee, employee_id)
    error = None

    if request.method == "POST":
        # Read the submitted values and strip extra spaces
        name = request.form.get("name", "").strip()
        email = request.form.get("email", "").strip()
        phone = request.form.get("phone_number", "").strip()
        job_title = request.form.get("job_title", "").strip()

        # Convert the dropdown values into booleans
        admin = request.form.get("admin") == "1"
        active = request.form.get("active") == "1"

        was_admin = employee.admin
        if not name or not email or not job_title:
            error = "Name, email, and job title are required."
        else:
            try:
                # Validate the phone number and add consistent dashes
                phone = format_phone(phone)
            except ValueError as message:
                # Display the helper function's error on the form
                error = str(message)
            else:
                # Update the existing employee
                employee.name = name
                employee.email = email
                employee.phone_number = phone or None
                employee.job_title = job_title
                employee.admin = admin
                employee.active = active

                if not was_admin and admin:
                    # Generate a random password for new admins
                    random_password = generate_random_password()
                    employee.password_hash = bcrypt.hashpw(
                        random_password.encode('utf-8'),
                        bcrypt.gensalt()
                    ).decode('utf-8')
                    send_admin_email(employee.email, random_password)
                    flash("Admin access granted. A temporary password has been sent to the employee's email.", "success")
                try:
                    # Save the changes to the db
                    db.session.commit()
                except IntegrityError:
                    # Undo the attempted changes if db rejects them
                    db.session.rollback()
                    error = "Could not save. That email may already be in use."
                else:
                    return redirect(url_for("employees"))

    # Check whether this employee has any assignment history
    has_assignment_history = db.session.execute(
        db.select(Assignment.assignment_id)
        .where(Assignment.employee_id == employee_id)
        .limit(1)
    ).first() is not None

    # Display the form and tell it whether assignment history exists
    return render_template(
        "edit_employee.html",
        employee=employee,
        error=error,
        has_assignment_history=has_assignment_history
    )
    

