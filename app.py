# Describe the assignment table so SQLAlchemy can use it
class Assignment(db.Model):
    __tablename__ = "assignment"

    # Unique ID generated by MySQL
    assignment_id = db.Column(db.Integer, primary_key=True)

    # Tool and employee involved in the assignment
    asset_id = db.Column(db.Integer, nullable=False)
    employee_id = db.Column(db.Integer, nullable=False)

    # Associate the assignment with a job or vehicle (optional)
    job_vehicle_number = db.Column(db.String(150))

    # Dates associated with the assignment
    date_assigned = db.Column(db.DateTime, nullable=False)
    expected_return_date = db.Column(db.Date)
    actual_return_date = db.Column(db.DateTime)

    # Record the tool's condition at checkout and return
    condition_when_assigned = db.Column(
        db.Enum("New", "Good", "Fair", "Poor", "Unknown"),
        nullable=False
    )
    condition_when_returned = db.Column(
        db.Enum("New", "Good", "Fair", "Poor", "Unknown")
    )

    # Missing fields, stay empty unless the tool is reported missing.
    missing_reported_date = db.Column(db.DateTime)
    missing_resolved_date = db.Column(db.DateTime)

    notes = db.Column(db.Text)

    # Tracks assignment status, True while assigned, including when the tool is missing
    active = db.Column(db.Boolean, nullable=False, default=True)


