@app.route("/login", methods=["GET", "POST"])
def login():

    if request.method == 'POST':
        username = request.form.get('username', '').strip()
        password = request.form.get('password', '').strip()

        mydb = db.engine.raw_connection()
        cursor = mydb.cursor()
    

        try:
            # Find the employee using their email only
            query = """
                SELECT email, password_hash
                FROM employee
                WHERE email = %s AND admin = TRUE;
            """
            cursor.execute(query, (username,))
            admin = cursor.fetchone()
            

        finally:
            cursor.close()
            mydb.close()

        # Make sure account and password hash exist before using bcrypt
        if admin and admin[1]:
            stored_hash = admin[1]

            # Convert string hash to bytes if necessary
            if isinstance(stored_hash, str):
                stored_hash = stored_hash.encode("utf-8")

            # Check submitted password
            if bcrypt.checkpw(
                password.encode("utf-8"),
                stored_hash
            ):
                session["user_email"] = admin[0]
                return redirect(url_for("dashboard"))

        flash("Invalid username or password.", "error")
        return render_template("login.html")

    return render_template("login.html")


