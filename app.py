# Describe the existing employee table so SQLAlchemy can use it
class Employee(db.Model):
    __tablename__ = "employee"

    # Unique ID generated by MySQL for each employee
    employee_id = db.Column(db.Integer, primary_key=True)

    # Basic employee information
    name = db.Column(db.String(150), nullable=False)
    email = db.Column(db.String(254), unique=True, nullable=False)
    phone_number = db.Column(db.String(30))
    job_title = db.Column(db.String(100), nullable=False)

    # Non-admin employees can have no password hash
    password_hash = db.Column(db.String(255))

    # Track employment status and permission to log in
    active = db.Column(db.Boolean, nullable=False, default=True)
    admin = db.Column(db.Boolean, nullable=False, default=False)

##Tool Table DB
class Tool(db.Model):
    __tablename__ = "tool"

    asset_id=db.Column(db.Integer, primary_key=True)

    tool_name = db.Column(db.String(150), nullable=False)
    category = db.Column(db.String(100), nullable=False)
    brand = db.Column(db.String(100))
    model = db.Column(db.String(100))
    description = db.Column(db.Text)

    purchase_date = db.Column(db.Date, nullable=False)
    price = db.Column(db.Numeric(12,2), nullable=False)

    asset_tag = db.Column(db.String(100), unique=True, nullable=False)
    serial_number = db.Column(db.String(150))

    status = db.Column(
        db.Enum("Available", "Assigned", "Missing", "Damaged", "Under Repair"), nullable = False)

    condition = db.Column(
        db.Enum("New", "Good", "Fair", "Poor", "Unknown"), nullable = False)
    
    notes = db.Column(db.Text)

# Describe the assignment table so SQLAlchemy can use it
class Assignment(db.Model):
    __tablename__ = "assignment"

    # Unique ID generated by MySQL
    assignment_id = db.Column(db.Integer, primary_key=True)

    # Tool and employee involved in the assignment
    asset_id = db.Column(db.Integer, nullable=False)
    employee_id = db.Column(db.Integer, nullable=False)

    # Associate the assignment with a job or vehicle (optional)
    job_vehicle_number = db.Column(db.String(150))

    # Dates associated with the assignment
    date_assigned = db.Column(db.DateTime, nullable=False)
    expected_return_date = db.Column(db.Date)
    actual_return_date = db.Column(db.DateTime)

    # Record the tool's condition at checkout and return
    condition_when_assigned = db.Column(
        db.Enum("New", "Good", "Fair", "Poor", "Unknown"),
        nullable=False
    )
    condition_when_returned = db.Column(
        db.Enum("New", "Good", "Fair", "Poor", "Unknown")
    )

    # Missing fields, stay empty unless the tool is reported missing.
    missing_reported_date = db.Column(db.DateTime)
    missing_resolved_date = db.Column(db.DateTime)

    notes = db.Column(db.Text)

    # Tracks assignment status, True while assigned, including when the tool is missing
    active = db.Column(db.Boolean, nullable=False, default=True)


