def check_in_tool(assignment_id):
    assignment = db.get_or_404(Assignment, assignment_id)
    tool = db.get_or_404(Tool, assignment.asset_id)
    employee = db.get_or_404(Employee, assignment.employee_id)
    error = None

    # Only allow these destinations when leaving the form
    # This lets all three Check In buttons use the same route
    source = request.args.get("source", "details")

    if source == "assignments":
        return_url = url_for("assignments")
    elif source == "tool":
        return_url = url_for("tool_details", asset_id=tool.asset_id)
    elif source == "inventory":
        return_url = url_for("tool_inventory")
    else:
        return_url = url_for(
            "assignment_details",
            assignment_id=assignment.assignment_id
        )

    # Ensure completed assignments cannot be checked in again
    if not assignment.active:
        flash("This assignment has already been checked in.", "error")
        return redirect(return_url)

    conditions = ["New", "Good", "Fair", "Poor", "Unknown"]
    statuses = ["Available", "Damaged", "Under Repair"]

    if request.method == "POST":
        condition = request.form.get("condition_when_returned", "")
        status = request.form.get("status", "")

        # Check submitted values 
        if condition not in conditions:
            error = "Please select a return condition."
        elif status not in statuses:
            error = "Please select a valid tool status."

        if error is None:
            try:
                # Lock the tool first
                # Refresh its values in case another admin changed it
                tool = db.session.execute(
                    db.select(Tool)
                    .where(Tool.asset_id == assignment.asset_id)
                    .with_for_update()
                    .execution_options(populate_existing=True)
                ).scalar_one()

                # Lock and refresh the assignment before checking it again
                assignment = db.session.execute(
                    db.select(Assignment)
                    .where(Assignment.assignment_id == assignment_id)
                    .with_for_update()
                    .execution_options(populate_existing=True)
                ).scalar_one()

                # Another admin may have checked it in while this form was open
                if not assignment.active:
                    db.session.rollback()
                    flash("This assignment has already been checked in.", "error")
                    return redirect(return_url)

                # Store UTC without timezone information
                returned_at = datetime.now(timezone.utc).replace(tzinfo=None)

                # Complete the existing assignment
                assignment.actual_return_date = returned_at
                assignment.condition_when_returned = condition
                assignment.active = False

                # Resolve an outstanding missing report when the tool returns
                if (assignment.missing_reported_date and assignment.missing_resolved_date is None):
                    assignment.missing_resolved_date = returned_at

                # Update the tool so its current information matches the return
                tool.condition = condition
                tool.status = status

                # Save both records together and release the locks
                db.session.commit()

            except IntegrityError:
                # Undo both updates and release locks if saving fails
                db.session.rollback()
                error = "The check-in could not be saved."
            else:
                return redirect(return_url)

    return render_template(
        "check_in_tool.html",
        assignment=assignment,
        tool=tool,
        employee=employee,
        conditions=conditions,
        statuses=statuses,
        return_url=return_url,
        error=error
    )



@app.route("/tools/import", methods=["POST"])
@login_required
def import_tools():

    if "file" not in request.files:
        flash("No file selected.", "error")
        return redirect(url_for("tool_inventory"))

    file = request.files["file"]

    if not file.filename:
        flash("No file selected.", "error")
        return redirect(url_for("tool_inventory"))

    if not file.filename.lower().endswith(".csv"):
        flash("Please upload a CSV file.", "error")
        return redirect(url_for("tool_inventory"))

    try:
        file_data = file.stream.read().decode("utf-8-sig")
        csv_reader = csv.DictReader(io.StringIO(file_data))

        required_columns = {
            "asset_tag",
            "tool_name",
            "brand",
            "model",
            "serial_number",
            "purchase_date",
            "price",
            "condition",
            "notes"
        }

        if csv_reader.fieldnames:
            csv_reader.fieldnames = [
                name.strip() for name in csv_reader.fieldnames
            ]

        if not required_columns.issubset(csv_reader.fieldnames or []):
            missing = required_columns - set(csv_reader.fieldnames or [])
            raise ValueError(
                f"Missing CSV columns: {', '.join(sorted(missing))}"
            )

        tools_to_add = []
        csv_asset_tags = set()
        csv_serial_numbers = set()

        # Load existing identifiers once instead of querying
        # the database separately for every CSV row.
        existing_asset_tags = set(
            db.session.scalars(db.select(Tool.asset_tag)).all()
        )

        existing_serial_numbers = set(
            db.session.scalars(
                db.select(Tool.serial_number)
                .where(Tool.serial_number.isnot(None))
            ).all()
        )

        for row in csv_reader:

            row_number = csv_reader.line_num

            asset_tag = (row["asset_tag"] or "").strip()
            tool_name = (row["tool_name"] or "").strip()
            brand = (row["brand"] or "").strip() or None
            model = (row["model"] or "").strip() or None
            serial_number = (
                (row["serial_number"] or "").strip() or None
            )
            condition = (row["condition"] or "").strip() or None
            notes = (row["notes"] or "").strip() or None

            purchase_date_text = (
                (row["purchase_date"] or "").strip()
            )

            if purchase_date_text:
                purchase_date = datetime.strptime(
                    purchase_date_text, "%m/%d/%Y"
                ).date()
            else:
                purchase_date = None

            price_text = (row["price"] or "").strip()
            price = Decimal(price_text) if price_text else None

            if not asset_tag or not tool_name:
                raise ValueError(
                    f"Missing asset tag or tool name on row {row_number}"
                )

            if asset_tag in existing_asset_tags:
                raise ValueError(
                    f"Asset tag {asset_tag} already exists."
                )

            if asset_tag in csv_asset_tags:
                raise ValueError(
                    f"Duplicate asset tag {asset_tag} in CSV."
                )

            if serial_number:
                if serial_number in existing_serial_numbers:
                    raise ValueError(
                        f"Serial number {serial_number} already exists."
                    )

                if serial_number in csv_serial_numbers:
                    raise ValueError(
                        f"Duplicate serial number {serial_number} in CSV."
                    )

                csv_serial_numbers.add(serial_number)

            csv_asset_tags.add(asset_tag)

            tool = Tool(
                asset_tag=asset_tag,
                tool_name=tool_name,
                brand=brand,
                model=model,
                serial_number=serial_number,
                purchase_date=purchase_date,
                price=price,
                condition=condition,
                notes=notes,
                status="Available"
            )

            tools_to_add.append(tool)

        # Insert all tools in one transaction
        db.session.add_all(tools_to_add)
        db.session.commit()

        flash(
            f"Successfully imported {len(tools_to_add)} tools.",
            "success"
        )

    except (ValueError, InvalidOperation) as error:
        db.session.rollback()
        flash(f"Import failed: {error}", "error")

    except Exception as error:
        db.session.rollback()
        print("IMPORT ERROR:", error, flush=True)
        flash(f"Import failed: {error}", "error")

    return redirect(url_for("tool_inventory"))


